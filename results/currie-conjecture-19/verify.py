class K:
    """a + b lam + c lam^2, lam real root of x^3 - 2x^2 + x - 1"""
    __slots__ = ('c',)
    def __init__(self, a=0, b=0, c=0): self.c = (Fr(a), Fr(b), Fr(c))
    @staticmethod
    def lift(x): return x if isinstance(x, K) else K(x)
