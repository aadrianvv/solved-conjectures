def find_conj(h, base):
    """return (u, direction) with base(c) u == u h(c) or h(c) u == u base(c), u up to length 30"""
    for L in range(0, 31):
        if all(len(x) >= L for x in base):
            u = base[0][:L]
            if is_conj(h, base, u): return (u, 'base(c)u=uh(c)')
        if all(len(x) >= L for x in h):
            u = h[0][:L]
            if is_conj(base, h, u): return (u, 'h(c)u=ubase(c)')
    return None
