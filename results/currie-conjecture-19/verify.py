def exact_factors_G(n):
    """length-n factors of G, certified: the set F of length-n factors of a prefix containing gamma^m(0) for all m with
       |gamma^(m-1)(0)| < n, closed under v -> Fact_n(gamma(v)), equals Fact_n(G) (PROOF.md, Lemma 2)"""
    N = 4 * n + 200
    while True:
        Pf = fixed_prefix(GAM, '0', N); F = facs(Pf, n)
        # condition (a) of Lemma 2: gamma^k(0) is a prefix of Pf for every k >= 0 with k = 0 or |gamma^(k-1)(0)| < n,
        # hence its length-n factors lie in F
        k, prev, cur = 0, None, '0'
        while k == 0 or len(prev) < n:
            assert Pf.startswith(cur), 'condition (a) of Lemma 2'
            prev, cur, k = cur, img(GAM, cur), k + 1
        # condition (b) of Lemma 2: closure under v -> Fact_n(gamma(v))
        if all(facs(img(GAM, v), n) <= F for v in F): return F
        N *= 2
