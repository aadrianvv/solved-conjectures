def walk_chain(chain, exts, bound_check=True):
    """follow the chain from L(G); at each step return the set of bispecials of the new language that are NOT images
       Lambda(u) of ordinary nonempty bispecials u of the previous language (they all have length <= bound)"""
    bound = 0          # max length of non-ordinary nonempty bispecial factors in the current language (0 = none)
    extras = []        # data of 'new' bispecials (not of the form Lambda(u) with u of the previous language), propagated
    for i, st in enumerate(chain):
        g = lang(chain[:i + 1])
        if st[0] == 'P':
            extras = [permute(b, st[1]) for b in extras]; continue
        newbound = max(1, 2 * bound + 1)                 # Lemma A/B (c): new bispecials have length <= 2m+1 (and >= 1)
        maxold = max([len(b['W']) for b in extras] + [0])
        B = max(newbound, 2 * maxold + 1) + 2
        act = brute_bispecials(g, B); act.pop('', None)
        prev = [b for b in extras if ordinary(b['E'])]
        prop = [lemma_step(b, st[0], st[1], st[2], exts[i]) for b in prev]
        propW = {b['W'] for b in prop}
        # every bispecial of length <= B is either an image of a G-type bispecial (checked in S4) or in prop or new
        new = [w for w in act if w not in propW and not from_G_images(i, w)]
        for w in new: assert len(w) <= newbound, (chain, i, w)      # Lemma A/B (c)
        newdata = [data_in(g, w, 80) for w in sorted(new, key=len)]
        for b in prop: assert act.get(b['W']) == b['E']
        extras = prop + newdata
        nonord = [b for b in extras if not ordinary(b['E'])]
        bound = max([len(b['W']) for b in nonord] + [0])
    return extras

